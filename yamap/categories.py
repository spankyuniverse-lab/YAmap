def list_categories() -> None:
    print("\n📂 Каталог категорий (аналог 2ГИС):\n")
    for group, items in CATEGORIES.items():
        print(f"  [{group}]")
        for item in items:
            print(f"    • {item}")
        print()
    print("Использование:")
